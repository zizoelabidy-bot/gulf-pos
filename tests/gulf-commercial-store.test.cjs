const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const os=require('node:os');
const crypto=require('node:crypto');
const {createCommercialStore}=require('../admin-app/commercial-store.cjs');
const dir=fs.mkdtempSync(path.join(os.tmpdir(),'gulf-commercial-test-'));
const file=path.join(dir,'registry.enc');
const key=crypto.randomBytes(32);
const encryption={isEncryptionAvailable:()=>true,encryptString:s=>{const iv=crypto.randomBytes(12),c=crypto.createCipheriv('aes-256-gcm',key,iv);return Buffer.concat([iv,c.update(s),c.final(),c.getAuthTag()]);},decryptString:b=>{const d=crypto.createDecipheriv('aes-256-gcm',key,b.subarray(0,12));d.setAuthTag(b.subarray(-16));return Buffer.concat([d.update(b.subarray(12,-16)),d.final()]).toString('utf8');}};
try{
const store=createCommercialStore(file,encryption);
assert.equal(store.read().customers.length,0);
const customer=store.record({kind:'customer',name:'Test Cafe',contact:'demo'}).customers[0];
assert.throws(()=>store.record({kind:'customer',name:'TEST CAFE'}),/already exists/);
const sub=store.record({kind:'subscription',customer_id:customer.id,start:'2026-12-01',end:'2027-11-30',amount:'100.125',reference:'contract-A'}).subscriptions[0];
assert.equal(sub.fee_fils,100125);
assert.throws(()=>store.record({kind:'subscription',customer_id:customer.id,start:'2027-01-01',end:'2027-06-01',amount:'1'}),/Overlapping/);
assert.throws(()=>store.record({kind:'subscription',customer_id:customer.id,start:'2027-02-30',end:'2027-06-01',amount:'1'}),/Invalid date/);
const pay={kind:'payment',subscription_id:sub.id,amount:'25.125',reference:'receipt-1',date:'2026-12-01'};
store.record(pay);
assert.throws(()=>store.record(pay),/Duplicate/);
assert.throws(()=>store.record({...pay,reference:'receipt-2',amount:'75.001'}),/exceeds/);
assert.throws(()=>store.record({...pay,reference:'receipt-3',amount:'1.0001'}),/Invalid KWD/);
store.record({...pay,reference:'receipt-2',amount:'75.000'});
const ticket=store.record({kind:'ticket',customer_id:customer.id,subject:'Printer issue',detail:'Local record'}).tickets[0];
store.record({kind:'close_ticket',ticket_id:ticket.id});
assert.throws(()=>store.record({kind:'close_ticket',ticket_id:ticket.id}),/Open ticket/);
const restored=createCommercialStore(file,encryption).read();
assert.equal(restored.payments.reduce((n,p)=>n+p.amount_fils,0),100125);
assert.equal(restored.tickets[0].status,'closed');
assert.ok(!fs.readFileSync(file).includes(Buffer.from('Test Cafe')));
assert.throws(()=>createCommercialStore(file,{...encryption,isEncryptionAvailable:()=>false}).read(),/unavailable/);
const corrupted=Buffer.from('corrupt');
fs.writeFileSync(file,corrupted);
assert.throws(()=>store.record({kind:'customer',name:'Other'}));
assert.deepEqual(fs.readFileSync(file),corrupted);
console.log('Commercial registry validation passed (mock encryption provider)');
}finally{fs.rmSync(dir,{recursive:true,force:true});}
